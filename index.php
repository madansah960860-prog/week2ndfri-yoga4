          <span class="eyebrow">What this is</span>
          <h2>A complete reference you can practice from tonight</h2>
        </div>
        <p class="lede">Every pose page says how to get in, what to feel for, how long to stay, and what to change if the shape does not suit you today.</p>
      </div>
      <div class="wrap prose stack reveal" style="padding-inline:0;margin-top:var(--s-5)">
        <p>Aruna Yoga Method is a written library. Every pose page tells you how to get in, what to feel for, how to breathe, how long to stay and what to do differently if the shape does not suit your body today. Every sequence page gives you an order, a hold time for each shape and a beginner path through it.</p>
        <p>There is no video wall here and no class schedule. The site is built for the fifteen minutes between putting the kids down and going to bed, for the ten minutes before a morning shower, for the hotel room floor and for the corner of a studio apartment where the mat only half unrolls.</p>
        <p>The page adapts, not you. Aruna switches automatically between a warm daylight look and a low-glare dark one based on your system setting, so it reads just as well on a kitchen floor at 7am as it does on a bedroom floor at 11pm. There is no brightness toggle to find, because there is nothing to configure.</p>
        <p class="small">This site provides general movement education only. It is not medical advice. Please read our <a href="health-safety-disclaimer.html">Health &amp; Safety Disclaimer</a> before you practice.</p>
