        <div>
          <span class="eyebrow">The hold timer</span>
          <h2>A timer built for holding still, not watching the clock</h2>
        </div>
        <p class="lede">Long holds are hard to time by feel. Counting breaths turns into counting seconds, and counting seconds turns into leaving early.</p>
      </div>
      <div class="wrap prose stack reveal" style="padding-inline:0;margin-top:var(--s-5)">
        <p>The timer in the corner of every page on this site counts a hold down and quietly dims the page while it runs, so the screen stops competing for your attention. It is a focus cue, not a mood setting — the light returns to normal the moment the hold finishes.</p>
        <p>Set it to thirty seconds for a standing shape, two minutes for a supported one, five minutes for a long Yin hold. On pose pages the suggested hold is one tap away. You can turn the dimming off in the timer panel if you would rather keep the page at full brightness throughout.</p>
        <p><a class="link-cta" href="#holdTimer">Try it in the corner of this page</a></p>
